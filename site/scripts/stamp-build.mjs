import {createHash} from 'node:crypto';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd(),files=[];
const excluded=new Set(['lib/build-info.ts','public/sw.js']);
async function walk(dir){for(const e of await readdir(path.join(root,dir),{withFileTypes:true})){const p=path.posix.join(dir,e.name);if(e.name.startsWith('.')||e.name==='node_modules')continue;if(e.isDirectory())await walk(p);else if(!excluded.has(p))files.push(p);}}
for(const dir of ['app','lib','public','scripts','db','drizzle'])await walk(dir);
files.push('package.json','package-lock.json','vite.config.ts');
const hash=createHash('sha256');
for(const f of [...new Set(files)].sort()){try{hash.update(f+'\0');hash.update(await readFile(path.join(root,f)));hash.update('\0');}catch(e){if(e.code!=='ENOENT')throw e;}}
const version=hash.digest('hex').slice(0,20);
await writeFile(path.join(root,'lib/build-info.ts'),`// Generated by scripts/stamp-build.mjs. Do not edit.\nexport const BUILD_ID = ${JSON.stringify(version)};\n`);
const worker=await readFile(path.join(root,'scripts/service-worker.js'),'utf8');
await writeFile(path.join(root,'public/sw.js'),worker.replaceAll('__MOA_BUILD_ID__',version));
console.log('Moa build '+version);
